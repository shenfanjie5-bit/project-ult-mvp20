def write_markdown(
    audits: list[CompanyAudit],
    summary: dict,
    out_path: Path,
    detailed: bool = False,
) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = []
    lines.append("# Injection Audit Report")
    lines.append("")
    lines.append(
        "> 三层数据架构覆盖度：overlay (LLM 衍生 schema, per-stock) + "
        "realtime (Tushare/FMP/Futu/akshare 灌入, per-stock) + "
        "L0 inherit (行业 overlay 共享, per-industry)。"
    )
    lines.append(
        "> Spec 总 dp_id 数 = "
        f"**{summary['spec_total']}**（来源：`docs/data_sources/coverage_audit.md` § 7）。"
    )
    lines.append("")

    total = summary["total_companies"]
    spec_total = summary["spec_total"]

    # === Summary ============================================================
    lines.append("## Summary")
    lines.append("")
    lines.append(f"- Total companies: **{total}**")
    if total:
        lines.append(
            f"- Average effective dp_ids: **{summary['avg_effective']:.1f} / "
            f"{spec_total}** = **{summary['avg_coverage_pct']:.1f}%**"
        )
    lines.append("- Per-layer averages:")
    lines.append(
        f"  - overlay Known: **{summary['avg_overlay_known']:.1f}** "
        "(LLM/codex 填; per-stock)"
    )
    lines.append(
        f"  - overlay Optionality: **{summary['avg_overlay_opt']:.1f}**"
    )
    lines.append(
        f"  - realtime injected: **{summary['avg_realtime']:.1f}** "
        "(Tushare/FMP/Futu/akshare)"
    )
    lines.append(
        f"  - L0 inherit (Known industry rows): **{summary['avg_l0_inherit']:.1f}**"
    )
    lines.append(
        f"- With ≥1 realtime value: **{summary['with_any_realtime']}** / "
        f"with zero: **{summary['with_zero_realtime']}**"
    )
    lines.append("")
    lines.append("| Market | Total | With realtime | Coverage |")
    lines.append("|---|---:|---:|---:|")
    for mkt in ("A", "HK", "US", "?"):
        t = summary["by_market"].get(mkt, 0)
        f = summary["by_market_filled"].get(mkt, 0)
        if t:
            lines.append(f"| {mkt} | {t} | {f} | {100*f//t}% |")
    lines.append("")

    # === Coverage Distribution =============================================
    lines.append("## Coverage Distribution")
    lines.append("")
    b = summary["buckets"]
    lines.append(f"- effective ≥ 50: **{b['ge_50']}** stocks")
    lines.append(f"- effective 40–49: **{b['ge_40']}**")
    lines.append(f"- effective 30–39: **{b['ge_30']}**")
    lines.append(f"- effective 20–29: **{b['ge_20']}**")
    lines.append(f"- effective < 20: **{b['lt_20']}**")
    lines.append("")

    # === Per-Industry Aggregates ===========================================
    lines.append("## Per-Industry Aggregates")
    lines.append("")
    lines.append(
        "| Industry | Stocks | overlay K avg | overlay Opt avg | "
        "realtime avg | L0 inherit | effective avg | best (ts, eff) | "
        "worst (ts, eff) |"
    )
    lines.append("|---|---:|---:|---:|---:|---:|---:|---|---|")
    for r in summary["industry_rollup"]:
        lines.append(
            f"| {r['industry_id']} | {r['stocks']} | "
            f"{r['avg_overlay_known']:.1f} | {r['avg_overlay_opt']:.1f} | "
            f"{r['avg_realtime']:.1f} | {r['avg_l0_inherit']:.1f} | "
            f"{r['avg_effective']:.1f} | "
            f"`{r['best_ts']}` ({r['best_effective']}) | "
            f"`{r['worst_ts']}` ({r['worst_effective']}) |"
        )
    lines.append("")

    # === Top sources contributing realtime dp_ids ==========================
    lines.append("## Top sources contributing realtime dp_ids")
    lines.append("")
    lines.append("| source | total rows | unique dp_ids | example dp_id |")
    lines.append("|---|---:|---:|---|")
    # Source rollup sorted by unique dp count desc, then rows desc.
    src_items = sorted(
        summary["source_rollup"].items(),
        key=lambda kv: (-kv[1]["unique_dp_ids"], -kv[1]["rows"]),
    )
    for name, info in src_items:
        lines.append(
            f"| `{name}` | {info['rows']} | {info['unique_dp_ids']} | "
            f"`{info['example']}` |"
        )
    lines.append("")

    # === Layer dp_id lists (kept for back-compat with old readers) ========
    lines.append(
        f"## Layer 1: overlay schema dp_ids "
        f"({len(summary['all_schema_dp_ids'])} unique across all companies)"
    )
    lines.append("")
    lines.append(
        "LLM-derived slots — codex fills these; data sources cannot. "
        "Each company has ~33 of these in its primary overlay."
    )
    lines.append("")
    for dp in summary["all_schema_dp_ids"]:
        lines.append(f"- `{dp}`")
    lines.append("")

    lines.append(
        f"## Layer 2: realtime dp_ids "
        f"({len(summary['all_realtime_dp_ids'])} unique across all companies)"
    )
    lines.append("")
    lines.append(
        "Data points actually written by collector (`realtime_current`). "
        "Exposed via the `realtime` field of `/api/project-ult/stock-overlay`."
    )
    lines.append("")
    for dp in summary["all_realtime_dp_ids"]:
        lines.append(f"- `{dp}`")
    lines.append("")

    lines.append(
        f"## Layer 3: L0 inherit dp_ids "
        f"({len(summary['all_l0_inherit_dp_ids'])} unique across all industries)"
    )
    lines.append("")
    lines.append(
        "`Known` industry-level rows from `config/industry_overlays/*.yaml`. "
        "Shared by every stock in an industry; not stored per-company."
    )
    lines.append("")
    for dp in summary["all_l0_inherit_dp_ids"]:
        lines.append(f"- `{dp}`")
    lines.append("")

    # === Per-Stock Detail ==================================================
    lines.append("## Per-Stock Detail")
    lines.append("")
    if detailed:
        lines.append(
            "| ts_code | name | market | industry | overlay K | overlay Opt | "
            "overlay Unk | realtime | L0 inh | effective | spec % | top sources |"
        )
        lines.append("|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---|")
    else:
        lines.append(
            "| ts_code | name | market | industry | overlay K | overlay Opt | "
            "realtime | L0 inh | effective | spec % |"
        )
        lines.append("|---|---|---|---|---:|---:|---:|---:|---:|---:|")
    for a in audits:
        if detailed:
            srcs = ", ".join(
                f"{k}:{v}"
                for k, v in sorted(
                    a.realtime_by_source.items(), key=lambda kv: -kv[1]
                )[:3]
            )
            lines.append(
                f"| `{a.ts_code}` | {a.name or '—'} | {a.market} | "
                f"{a.industry_id} | {a.overlay_known} | {a.overlay_optionality} | "
                f"{a.overlay_unknown_real} | {a.realtime_dps} | "
                f"{a.industry_l0_known} | {a.effective_dps} | "
                f"{a.coverage_pct:.1f}% | {srcs} |"
            )
        else:
            lines.append(
                f"| `{a.ts_code}` | {a.name or '—'} | {a.market} | "
                f"{a.industry_id} | {a.overlay_known} | {a.overlay_optionality} | "
                f"{a.realtime_dps} | {a.industry_l0_known} | "
                f"{a.effective_dps} | {a.coverage_pct:.1f}% |"
            )
    lines.append("")

    # === Companies with zero realtime (full list) =========================
    zero = [a for a in audits if not a.realtime_dps]
    if zero:
        lines.append(f"## Companies with zero realtime values ({len(zero)})")
        lines.append("")
        lines.append(
            "These need source attention — collector may be skipping them "
            "(permissions / suspended / unknown ticker mapping)."
        )
        lines.append("")
        lines.append("| ts_code | market | name | industry |")
        lines.append("|---|---|---|---|")
        for a in zero:
            lines.append(
                f"| `{a.ts_code}` | {a.market} | {a.name or '—'} | "
                f"{a.industry_id} |"
            )
        lines.append("")

    out_path.write_text("\n".join(lines), encoding="utf-8")


def write_csv(audits: list[CompanyAudit], out_path: Path) -> None:
    """Write the per-company three-layer CSV.

    Columns are the new canonical set described in the U3 brief; legacy
    readers should switch to ``effective_dps`` / ``coverage_pct``.
    """

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow([
            "ts_code", "name", "market", "industry_ids",
            "overlay_total",
            "overlay_known", "overlay_optionality",
            "overlay_unknown", "overlay_inactive", "overlay_na",
            "realtime_dps", "industry_l0_known",
            "effective_dps", "spec_total", "spec_coverage_pct",
            "realtime_by_source",
            "overlay_known_dp_ids", "overlay_opt_dp_ids",
            "realtime_dp_ids", "industry_l0_dp_ids",
        ])
        for a in audits:
            w.writerow([
                a.ts_code, a.name or "", a.market,
                "|".join(a.industry_ids),
                a.overlay_total,
                a.overlay_known, a.overlay_optionality,
                a.overlay_unknown_real, a.overlay_inactive, a.overlay_na,
                a.realtime_dps, a.industry_l0_known,
                a.effective_dps, a.spec_total,
                f"{a.coverage_pct:.2f}",
                json.dumps(a.realtime_by_source, ensure_ascii=False),
                ";".join(a.overlay_known_dp_ids),
                ";".join(a.overlay_opt_dp_ids),
                ";".join(a.realtime_dp_ids),
                ";".join(a.industry_l0_dp_ids),
            ])
